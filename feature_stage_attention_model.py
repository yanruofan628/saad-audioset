class FeatureWeightedModel(nn.Module):
    """
    Learns per-feature importance on top of global statistics.
    """

    def __init__(self, feature_dim: int, hidden_dim: int = 64, dropout: float = 0.2):
        super().__init__()
        self.feature_gate = nn.Sequential(
            nn.Linear(feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, feature_dim),
            nn.Sigmoid(),
        )
        self.regressor = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        weights = self.feature_gate(x)
        gated = x * weights
        pred = torch.sigmoid(self.regressor(gated)).squeeze(-1)
        return pred, weights


class FeatureStageAttentionModel(nn.Module):
    """
    Joint stage (time) + feature attention.
    Input shape: (batch, n_stages, feature_dim)
    """

    def __init__(self, n_stages: int, feature_dim: int, hidden_dim: int = 64, dropout: float = 0.2):
        super().__init__()
        self.n_stages = n_stages
        self.feature_dim = feature_dim

        self.stage_attn = nn.Sequential(
            nn.Linear(feature_dim, hidden_dim),
            nn.Tanh(),
            nn.Linear(hidden_dim, 1),
        )
        self.feature_gate = nn.Sequential(
            nn.Linear(feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, feature_dim),
            nn.Sigmoid(),
        )
        self.regressor = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        # x: (batch, n_stages, feature_dim)
        stage_scores = self.stage_attn(x).squeeze(-1)  # (batch, n_stages)
        stage_weights = torch.softmax(stage_scores, dim=1)
        context = torch.sum(stage_weights.unsqueeze(-1) * x, dim=1)  # (batch, feature_dim)

        feature_weights = self.feature_gate(context)
        gated = context * feature_weights
        pred = torch.sigmoid(self.regressor(gated)).squeeze(-1)
        return pred, stage_weights, feature_weights


class SimpleTemporalModel(nn.Module):
    """
    极简时间建模：学习时间权重进行加权平均
    最简单的时序处理，避免过拟合
    Input shape: (batch, n_stages, feature_dim)
    """

    def __init__(self, n_stages: int, feature_dim: int, hidden_dim: int = 16):
        super().__init__()
        self.n_stages = n_stages
        self.feature_dim = feature_dim

        # 学习到的时间权重（最简单的时序建模）
        self.time_weights = nn.Parameter(torch.ones(n_stages) / n_stages)

        # 简单的特征聚合
        self.feature_agg = nn.Sequential(
            nn.Linear(feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, hidden_dim),
        )

        # 预测头
        self.regressor = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Linear(hidden_dim // 2, 1),
        )

        # 简单初始化
        for param in self.parameters():
            if param.dim() > 1:
                nn.init.xavier_uniform_(param, gain=0.1)
            else:
                nn.init.constant_(param, 0)

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        极简时间建模：学习时间权重进行加权平均

        Args:
            x: (batch, n_stages, feature_dim) - 分阶段特征

        Returns:
            pred: 预测值
            time_weights: 学习到的时间权重
        """
        batch_size = x.size(0)

        # 确保时间权重是概率分布
        time_weights = torch.softmax(self.time_weights, dim=0)

        # 对每个时间步的特征进行聚合
        stage_features = []
        for t in range(self.n_stages):
            stage_feat = self.feature_agg(x[:, t, :])  # (batch, hidden_dim)
            stage_features.append(stage_feat)

        # 堆叠所有时间步
        stage_features = torch.stack(stage_features, dim=1)  # (batch, n_stages, hidden_dim)

        # 时间加权平均
        weighted_features = torch.sum(stage_features * time_weights.unsqueeze(0).unsqueeze(-1), dim=1)  # (batch, hidden_dim)

        # 预测
        pred = self.regressor(weighted_features).squeeze(-1)  # (batch,)

        return pred, time_weights

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        使用GRU进行时间累加，而不是注意力聚合

        Args:
            x: (batch, n_stages, feature_dim) - 分阶段特征

        Returns:
            pred: 预测概率
            accumulation_weights: 特征权重
        """
        batch_size = x.size(0)

        # 确保memory_decay在合理范围内
        clamped_decay = torch.clamp(self.memory_decay, self.min_decay, self.max_decay)

        # 初始化积累状态
        accumulation_state = torch.zeros(batch_size, self.feature_dim, device=x.device)

        # GRU累加过程
        for t in range(self.n_stages):
            current_input = x[:, t, :]  # (batch, feature_dim)

            # GRU更新
            new_state = self.gru_cell(current_input, accumulation_state)

            # 应用记忆衰减（生物机制）
            accumulation_state = new_state * clamped_decay + current_input * (1 - clamped_decay)

        # 最终积累状态作为上下文
        context = accumulation_state  # (batch, feature_dim)

        # 特征门控
        feature_weights = self.feature_gate(context)
        gated = context * feature_weights

        # 预测（回归任务，直接输出连续值）
        pred = self.regressor(gated).squeeze(-1)

        # 调试：确保输出是合理的概率值
        print(f"DEBUG: pred range: {pred.min().item():.4f} - {pred.max().item():.4f}")
        print(f"DEBUG: pred mean: {pred.mean().item():.4f}")
        print(f"DEBUG: pred std: {pred.std().item():.4f}")

        return pred, feature_weights


class SharedEarComparisonModel(nn.Module):
    """
    Scores left/right ears with shared weights, then compares.
    """

    def __init__(self, ear_feature_dim: int, hidden_dim: int = 64, dropout: float = 0.2):
        super().__init__()
        self.feature_gate = nn.Sequential(
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, ear_feature_dim),
            nn.Sigmoid(),
        )
        self.scorer = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def _score(self, ear_feat: torch.Tensor):
        gated = ear_feat * self.feature_gate(ear_feat)
        return self.scorer(gated).squeeze(-1)

    def forward(self, left_feat: torch.Tensor, right_feat: torch.Tensor):
        left_score = self._score(left_feat)
        right_score = self._score(right_feat)
        pred = torch.sigmoid(left_score - right_score)
        return pred, left_score, right_score


class IndependentEarComparisonModel(nn.Module):
    """
    Scores left/right ears with independent weights before comparison.
    """

    def __init__(self, ear_feature_dim: int, hidden_dim: int = 64, dropout: float = 0.2):
        super().__init__()
        self.left_gate = nn.Sequential(
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, ear_feature_dim),
            nn.Sigmoid(),
        )
        self.right_gate = nn.Sequential(
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, ear_feature_dim),
            nn.Sigmoid(),
        )
        self.left_scorer = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )
        self.right_scorer = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def forward(self, left_feat: torch.Tensor, right_feat: torch.Tensor):
        left_score = self.left_scorer(left_feat * self.left_gate(left_feat)).squeeze(-1)
        right_score = self.right_scorer(right_feat * self.right_gate(right_feat)).squeeze(-1)
        pred = torch.sigmoid(left_score - right_score)
        return pred, left_score, right_score


class AdditiveTimeAttention(nn.Module):
    """Additive attention over the time dimension."""

    def __init__(self, input_dim: int, hidden_dim: int):
        super().__init__()
        self.proj = nn.Linear(input_dim, hidden_dim)
        self.v = nn.Linear(hidden_dim, 1, bias=False)

    def forward(self, seq: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        # seq: (batch, T, input_dim)
        u = torch.tanh(self.proj(seq))  # (batch, T, hidden_dim)
        scores = self.v(u).squeeze(-1)  # (batch, T)
        weights = torch.softmax(scores, dim=1)
        context = torch.bmm(weights.unsqueeze(1), seq).squeeze(1)
        return context, weights


class PerFeatureTimeAttention(nn.Module):
    """Time attention applied per feature dimension independently."""

    def __init__(self, n_features: int, attn_hidden: int = 32):
        super().__init__()
        # Create separate attention for each feature dimension
        self.feature_attentions = nn.ModuleList([
            AdditiveTimeAttention(1, attn_hidden) for _ in range(n_features)
        ])

    def forward(self, seq: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        # seq: (batch, T, n_features)
        batch_size, T, n_features = seq.shape

        # Apply attention to each feature independently
        attended_features = []
        attention_weights = []

        for i in range(n_features):
            # Extract i-th feature across time: (batch, T, 1)
            feature_seq = seq[:, :, i:i+1]
            # Apply attention: returns (batch, 1), (batch, T)
            context, weights = self.feature_attentions[i](feature_seq)
            attended_features.append(context.squeeze(-1))  # (batch,)
            attention_weights.append(weights)  # (batch, T)

        # Stack attended features: (batch, n_features)
        context_vector = torch.stack(attended_features, dim=1)
        # Stack weights: (batch, n_features, T)
        weights_tensor = torch.stack(attention_weights, dim=1)

        return context_vector, weights_tensor


class StageAwareSharedComparisonUnified(nn.Module):
    """
    Stage attention shared across ears with per-feature time weights, feature gates shared.
    """

    def __init__(self, ear_feature_dim: int, attn_hidden: int = 64, hidden_dim: int = 64, dropout: float = 0.2):
        super().__init__()
        self.shared_attn = PerFeatureTimeAttention(ear_feature_dim, attn_hidden)
        self.feature_gate = nn.Sequential(
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, ear_feature_dim),
            nn.Sigmoid(),
        )
        self.scorer = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def forward(self, left_seq: torch.Tensor, right_seq: torch.Tensor):
        left_context, left_weights = self.shared_attn(left_seq)
        right_context, right_weights = self.shared_attn(right_seq)
        gate = self.feature_gate(left_context)  # shared gate applied to both contexts
        left_score = self.scorer(left_context * gate).squeeze(-1)
        right_score = self.scorer(right_context * gate).squeeze(-1)
        pred = torch.sigmoid(left_score - right_score)
        return pred, left_weights, right_weights, gate, gate  # return gate twice for compatibility



class StageAwareSharedComparisonModel(nn.Module):
    """
    Shared ear weights with per-ear time attention over stage features.
    """

    def __init__(self, ear_feature_dim: int, attn_hidden: int = 64, hidden_dim: int = 64, dropout: float = 0.2):
        super().__init__()
        self.left_attn = AdditiveTimeAttention(ear_feature_dim, attn_hidden)
        self.right_attn = AdditiveTimeAttention(ear_feature_dim, attn_hidden)
        self.feature_gate = nn.Sequential(
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, ear_feature_dim),
            nn.Sigmoid(),
        )
        self.scorer = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(ear_feature_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, 1),
        )

    def forward(self, left_seq: torch.Tensor, right_seq: torch.Tensor):
        left_context, left_weights = self.left_attn(left_seq)
        right_context, right_weights = self.right_attn(right_seq)
        left_gate = self.feature_gate(left_context)
        right_gate = self.feature_gate(right_context)
        left_score = self.scorer(left_context * left_gate).squeeze(-1)
        right_score = self.scorer(right_context * right_gate).squeeze(-1)
        pred = torch.sigmoid(left_score - right_score)
        return pred, left_weights, right_weights, left_gate, right_gate


