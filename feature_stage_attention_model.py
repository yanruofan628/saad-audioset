def aggregate_stage_aware_weights(model, loader: DataLoader):
    if loader is None:
        return None
    model.eval()
    left_stage_sum = right_stage_sum = left_feat_sum = right_feat_sum = None
    left_per_feature_weights = right_per_feature_weights = None
    total = 0
    is_per_feature_model = isinstance(model, StageAwareSharedComparisonUnified)

    with torch.no_grad():
        for left_seq, right_seq, _ in loader:
            left_seq = left_seq.to(DEVICE)
            right_seq = right_seq.to(DEVICE)
            pred, left_stage, right_stage, left_feat_gate, right_feat_gate = model(left_seq, right_seq)
            batch_size = left_seq.size(0)
            total += batch_size

            # Handle different weight shapes
            if left_stage.dim() == 3:  # (batch, n_features, T) - PerFeatureTimeAttention
                # For per-feature visualization, collect all weights
                if left_per_feature_weights is None:
                    left_per_feature_weights = left_stage.sum(dim=0)  # (n_features, T)
                    right_per_feature_weights = right_stage.sum(dim=0)  # (n_features, T)
                else:
                    left_per_feature_weights += left_stage.sum(dim=0)
                    right_per_feature_weights += right_stage.sum(dim=0)

                # Average across features for stage weights: (batch, T)
                ls = left_stage.mean(dim=1).sum(dim=0)
                rs = right_stage.mean(dim=1).sum(dim=0)
            else:  # (batch, T) - regular AdditiveTimeAttention
                ls = left_stage.sum(dim=0)
                rs = right_stage.sum(dim=0)

            lf = left_feat_gate.detach().sum(dim=0)
            rf = right_feat_gate.detach().sum(dim=0)
            left_stage_sum = ls if left_stage_sum is None else left_stage_sum + ls
            right_stage_sum = rs if right_stage_sum is None else right_stage_sum + rs
            left_feat_sum = lf if left_feat_sum is None else left_feat_sum + lf
            right_feat_sum = rf if right_feat_sum is None else right_feat_sum + rf

    if total == 0:
        return None

    left_stage_mean = (left_stage_sum / total).cpu().numpy()
    right_stage_mean = (right_stage_sum / total).cpu().numpy()
    left_feat_mean = (left_feat_sum / total).cpu().numpy()
    right_feat_mean = (right_feat_sum / total).cpu().numpy()

    result = {
        "left_stage": left_stage_mean,
        "right_stage": right_stage_mean,
        "left_feature": left_feat_mean,
        "right_feature": right_feat_mean,
    }

    if is_per_feature_model and left_per_feature_weights is not None:
        # Store per-feature time weights for visualization
        result["left_per_feature_time"] = (left_per_feature_weights / total).cpu().numpy()
        result["right_per_feature_time"] = (right_per_feature_weights / total).cpu().numpy()

    if isinstance(model, StageAwareSharedComparisonUnified):
        result["shared_stage"] = left_stage_mean  # same for both

    return result


