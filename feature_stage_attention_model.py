"""
Feature & Stage Attention Models
================================

Four lightweight variants that run on the existing 5 s preference dataset:

1. FeatureWeightedModel – learns per-feature importance after aggregating
   across time (mean/std of left-right differences).
2. FeatureStageAttentionModel – learns both stage-level (1 s segments) and
   feature-level attention jointly, providing time × feature interpretability.
3. FeatureStageGRUModel – uses GRU for temporal accumulation instead of attention.
4. Comparison models – various ear comparison strategies with temporal modeling.

All models reuse the cached multi-feature datasets generated by
attention_loudness_model.py (500 ms resolution). This script simply builds
stage-wise statistics on top and trains the new attention heads.
"""

