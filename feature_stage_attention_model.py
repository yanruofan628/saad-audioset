def test_gru_model():
    """测试GRU模型是否正常工作"""
    print("=== 测试FeatureStageGRUModel ===")

    # 创建模型
    model = FeatureStageGRUModel(n_stages=5, feature_dim=10, hidden_dim=32)
    model.eval()

    # 创建测试数据 (回归任务)
    batch_size = 4
    x = torch.randn(batch_size, 5, 10)  # (batch, n_stages, feature_dim)
    y = torch.rand(batch_size)  # 连续标签 (0-1)

    print(f"输入形状: {x.shape}")
    print(f"标签范围: {y.min().item():.4f} - {y.max().item():.4f}")

    # 前向传播
    with torch.no_grad():
        pred, weights = model(x)

    print(f"预测范围: {pred.min().item():.4f} - {pred.max().item():.4f}")
    print(f"预测均值: {pred.mean().item():.4f}")
    print(f"预测标准差: {pred.std().item():.4f}")
    print(f"权重形状: {weights.shape}")

    # 计算MSE
    mse = ((pred - y) ** 2).mean().item()
    print(f"MSE: {mse:.4f}")

    return mse < 1.0  # 如果MSE小于1，说明模型基本正常


