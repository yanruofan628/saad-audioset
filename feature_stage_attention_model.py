def _compute_stage_features(
    sample: np.ndarray,
    n_stages: int,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Convert a (2*F, T) sample into:
      - stage_features: (n_stages, feat_dim) where feat_dim = 2*F (mean+std diff)
      - global_features: (feat_dim,) overall mean/std diff
    """
    channels, time_steps = sample.shape
    assert channels % 2 == 0, "Sample must contain left/right feature stacks."
    n_features = channels // 2

    left = sample[:n_features]
    right = sample[n_features:]
    diff = left - right  # (F, T)

    left_mean = left.mean(axis=1)
    left_std = left.std(axis=1)
    right_mean = right.mean(axis=1)
    right_std = right.std(axis=1)

    global_diff = np.concatenate([left_mean - right_mean, left_std - right_std], axis=0)
    left_global = np.concatenate([left_mean, left_std], axis=0)
    right_global = np.concatenate([right_mean, right_std], axis=0)

    # Stage stats
    frames_per_stage = max(1, time_steps // n_stages)
    stage_diff_vectors: List[np.ndarray] = []
    stage_left_vectors: List[np.ndarray] = []
    stage_right_vectors: List[np.ndarray] = []
    for s in range(n_stages):
        start = s * frames_per_stage
        end = time_steps if s == n_stages - 1 else min(time_steps, (s + 1) * frames_per_stage)
        slice_diff = diff[:, start:end]
        slice_left = left[:, start:end]
        slice_right = right[:, start:end]
        if slice_diff.size == 0:
            diff_mean = np.zeros(n_features, dtype=np.float32)
            diff_std = np.zeros(n_features, dtype=np.float32)
            left_mean = np.zeros(n_features, dtype=np.float32)
            left_std = np.zeros(n_features, dtype=np.float32)
            right_mean = np.zeros(n_features, dtype=np.float32)
            right_std = np.zeros(n_features, dtype=np.float32)
        else:
            diff_mean = slice_diff.mean(axis=1)
            diff_std = slice_diff.std(axis=1)
            left_mean = slice_left.mean(axis=1)
            left_std = slice_left.std(axis=1)
            right_mean = slice_right.mean(axis=1)
            right_std = slice_right.std(axis=1)
        stage_diff_vectors.append(np.concatenate([diff_mean, diff_std], axis=0))
        stage_left_vectors.append(np.concatenate([left_mean, left_std], axis=0))
        stage_right_vectors.append(np.concatenate([right_mean, right_std], axis=0))

    stage_features = np.stack(stage_diff_vectors, axis=0)  # (n_stages, feat_dim)
    stage_left = np.stack(stage_left_vectors, axis=0)
    stage_right = np.stack(stage_right_vectors, axis=0)
    return (
        stage_features.astype(np.float32),
        global_diff.astype(np.float32),
        left_global.astype(np.float32),
        right_global.astype(np.float32),
        stage_left.astype(np.float32),
        stage_right.astype(np.float32),
    )


class StageFeatureDataset(Dataset):
    """
    Materializes global/stage features for all samples to enable
    fast subset access during K-fold cross-validation.
    """

    def __init__(
        self,
        base_dataset: Dataset,
        stage_seconds: float = DEFAULT_STAGE_SECONDS,
        feature_configs: Optional[List[Tuple[str, bool]]] = None,
    ):
        self.base = base_dataset
        sample, _ = self.base[0]
        _, time_steps = sample.shape
        frames_per_stage = max(1, int(round((stage_seconds * SR) / HOP)))
        self.n_stages = max(1, time_steps // frames_per_stage)
        self.feat_dim = (sample.shape[0] // 2) * 2  # mean+std per feature

        if feature_configs:
            base_names = [cfg[0] for cfg in feature_configs]
        else:
            base_names = [f"feat_{i+1}" for i in range(self.feat_dim // 2)]
        self.stage_labels = [f"Stage {i + 1}" for i in range(self.n_stages)]
        ear_labels: List[str] = []
        for name in base_names:
            ear_labels.append(f"{name}_mean")
            ear_labels.append(f"{name}_std")
        self.ear_feature_labels = ear_labels

        global_list: List[np.ndarray] = []
        left_list: List[np.ndarray] = []
        right_list: List[np.ndarray] = []
        stage_list: List[np.ndarray] = []
        left_stage_list: List[np.ndarray] = []
        right_stage_list: List[np.ndarray] = []
        target_list: List[float] = []

        for idx in range(len(self.base)):
            feat, tgt = self.base[idx]
            (
                stage_feat,
                global_feat,
                left_global,
                right_global,
                stage_left,
                stage_right,
            ) = _compute_stage_features(feat, self.n_stages)
            stage_list.append(stage_feat)
            global_list.append(global_feat)
            left_list.append(left_global)
            right_list.append(right_global)
            left_stage_list.append(stage_left)
            right_stage_list.append(stage_right)
            target_list.append(float(tgt))

        self.global_feats = np.stack(global_list, axis=0)
        self.stage_feats = np.stack(stage_list, axis=0)
        self.left_globals = np.stack(left_list, axis=0)
        self.right_globals = np.stack(right_list, axis=0)
        self.stage_left_feats = np.stack(left_stage_list, axis=0)
        self.stage_right_feats = np.stack(right_stage_list, axis=0)
        self.targets = np.asarray(target_list, dtype=np.float32)
        self.left_feat_dim = self.left_globals.shape[1]
        self.ear_stage_feat_dim = self.stage_left_feats.shape[2]

    def __len__(self) -> int:
        return self.global_feats.shape[0]

    def __getitem__(self, idx: int):
        global_feat = torch.from_numpy(self.global_feats[idx])
        stage_feat = torch.from_numpy(self.stage_feats[idx])
        target = torch.tensor(self.targets[idx], dtype=torch.float32)
        return global_feat, stage_feat, target


